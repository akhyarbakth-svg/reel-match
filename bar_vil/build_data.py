# match_data.json -> data.js (loaded by index.html)
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
TEAM={'BAR':'A','VIL':'E'} # A = Barcelona (home, attacks +x), E = Villarreal (attacks -x)
NAMES={(5,'VIL'):'TAJON BUCHANAN',(7,'VIL'):'TANI OLUWASEYI',(57,'BAR'):'GERARD MARTÍN',(61,'BAR'):'FERMÍN LÓPEZ',(67,'VIL'):'PAU NAVARRO'}
KEEPER={'151001':'GULÁCSI','1167220':'JOAN GARCÍA'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, added, team, type) -> (beat, name)
CHANCES={(23,None,'BAR','Post'):('post','LAMINE YAMAL'),   # VAR-awarded penalty, FotMob/Opta: off the woodwork
         (45,3,'BAR','AttemptSaved'):('save','ERIC GARCÍA')}  # 0.30 xG, saved by Gulácsi (Fermín's 45+3 follow-up was blocked)
REDN={'Pau Navarro':'PAU NAVARRO'}
OG_VIS=0.35 # an own goal has no shot xG: give its spike a fixed visual height so it still shows on the surface
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def key(s): return (s['min'],s['add'],s['team'],s['type'])
def beat(s): return key(s) in CHANCES and (s['type']!='AttemptSaved' or not s['blocked'])
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to 95
    a=s.get('add') or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s.get('add'); return f"{s['min']}+{a}'" if a else f"{s['min']}'"
def loc(s): # FotMob x: 0..105 towards the goal the shooter's team attacks, y: 0..68
    sg=1 if TEAM[s['team']]=='A' else -1; return round(sg*(s['x']-52.5),2), round(sg*(s['y']-34),2)
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for e in D['events']:
    if e['type']=='card' and e['card'] in('Red','YellowRed'):
        T=TEAM[e['team']]; why='SECOND YELLOW' if e['card']=='YellowRed' else (e['reason'] or '').upper(); m=clock(e)
        ev.append((m+0.01,f"{{m:{m},team:'{T}',type:'red',name:'{REDN[e['player']]}',min:\"{label(e)}\",why:'{why}'}}"))
for s in shots:
    x,z=loc(s)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else '')
        if s['ownGoal']: # credited to the other side; the location is already in the defender's frame, i.e. at the end the scorers attack
            T='A' if TEAM[s['team']]=='E' else 'E'
            ev.append((m,f"{{m:{m},team:'{T}',type:'goal',og:1,word:'OWN GOAL',name:'{NAMES[(s['min'],s['team'])]}',min:\"{lab}\",xg:0,vh:{OG_VIS},x:{x},z:{z}}}"))
        else:
            T=TEAM[s['team']]
            ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[(s['min'],s['team'])]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    elif beat(s):
        T=TEAM[s['team']]; k,name=CHANCES[key(s)]; m=clock(s)
        extra=",pen:1,word:'MISSED'" if s['situation']=='Penalty' else ''
        by=f",by:'{KEEPER[str(s['keeperId'])]}'" if k=='save' else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}{extra}}}"))
    else:
        T=TEAM[s['team']]
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev,key=lambda p:p[0])]
# 45.5 = first-half stoppage; 90.5 / 90.75 = second-half stoppage (+5), stretched to the 95' clock end
mom=[[{90.5:92.5,90.75:94.5}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[95,0]]
emit("const EVENTS=[ // team: A = Barcelona, E = Villarreal · xG + shot location from FotMob (Opta)\n "+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Barcelona on top; 45.5 / 92.5+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
