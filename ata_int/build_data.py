# match_data.json -> data.js (loaded by index.html) · Atalanta 4-4 Inter, Serie A MD12, 22 Nov 2026
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
HOME,AWAY='ATA','INT' # A = Atalanta (attacks +x, nearest the camera), E = Inter
# goal callout names; Pio Esposito's third (52') gets the HAT-TRICK word
NAMES={(16,'INT'):'PIO ESPOSITO',(32,'INT'):'PIO ESPOSITO',(35,'ATA'):'ELJIF ELMAS',(52,'INT'):'PIO ESPOSITO',
       (72,'ATA'):'DE KETELAERE',(76,'INT'):'PETAR SUČIĆ',(80,'ATA'):'DE KETELAERE',(90,'ATA'):'FRANCK KESSIÉ'}
WORD={(52,'INT'):'HAT-TRICK'}
# no big misses get their own beat today: eight goals carry the reel (the 0.49 De Ketelaere save at 80' pops just before his goal)
CHANCES={}
OUT=[]
def emit(t): OUT.append(t)
def beat(s): return (s['min'],s['team'],s['type']) in CHANCES
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to END
    a=s['add'] or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
# per-shot xG is scaled per team and half to FotMob's official half totals (Inter's 1st-half shots sum to 1.70 against an official 1.68),
# so the live scoreboard counter lands exactly on the FT stat panel
xi={HOME:0,AWAY:1}; SCALE={}
for per,half in (('FirstHalf',lambda s:s['min']<=45),('SecondHalf',lambda s:s['min']>45)):
    for t in (HOME,AWAY):
        raw=sum(s['xg'] for s in D['shots'] if s['team']==t and half(s)); off=float(D['stats'][per]['expected_goals'][xi[t]])
        SCALE[(t,per)]=off/raw if raw else 1
def xg(s): return s['xg']*SCALE[(s['team'],'FirstHalf' if s['min']<=45 else 'SecondHalf')]
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
ev,sh=[],[]
for e in D['events']:
    T='A' if e.get('team')==HOME else 'E'
    if e['type']=='var':
        ev.append((e['min']+0.01,f"{{m:{e['min']},team:'{T}',type:'var',name:'{e['player'].upper()}',min:\"{e['min']}'\",why:'{e['decision'][1].upper()}'}}"))
    elif e['type']=='card' and e['card'] in('Red','YellowRed'):
        why='SECOND YELLOW' if e['card']=='YellowRed' else (e['reason'] or '').upper()
        ev.append((e['min']+0.01,f"{{m:{e['min']},team:'{T}',type:'red',name:'{e['player'].upper()}',min:\"{e['min']}'\",why:'{why}'}}"))
for s in shots:
    T='A' if s['team']==HOME else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Atalanta attack +x, Inter attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else ''); k=(s['min'],s['team'])
        w=f",word:'{WORD[k]}'" if k in WORD else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[k]}',min:\"{lab}\",xg:{xg(s):.4f},x:{x},z:{z}{w}}}"))
    elif beat(s):
        k,name,*by=CHANCES[(s['min'],s['team'],s['type'])]; m=clock(s); by=f",by:'{by[0]}'" if by else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{xg(s):.4f},x:{x},z:{z}{by}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{xg(s):.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 45.5 = first-half stoppage (+1); 90.5 / 90.75 = second-half stoppage (+4, last shot 90+5), stretched to the 96' clock end
mom=[[{90.5:92.5,90.75:95}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[96,0]]
emit('const EVENTS=[ // team: A = Atalanta, E = Inter · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Atalanta on top; 45.5 / 92.5+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
