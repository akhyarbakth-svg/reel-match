# match_data.json -> data.js (loaded by index.html)
# Real Madrid 2-1 Celta Vigo, LaLiga MD13, 21 Nov 2026 (FotMob match 5868139)
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
HOME='RMA' # team A = Real Madrid (attacks +x, nearest the camera), team E = Celta
NAMES={(6,'CEL'):'PABLO DURÁN',(66,'RMA'):'JUDE BELLINGHAM',(85,'RMA'):'CARLOS ESPÍ'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, team, type) -> (beat, name[, keeper])
# Mbappé's 39' penalty went over the bar (FotMob goalCrossedZ 4.58 m, crossbar 2.44 m)
CHANCES={(14,'RMA','Miss'):('miss','BERNARDO SILVA'),(39,'RMA','Miss'):('miss','KYLIAN MBAPPÉ'),
         (85,'RMA','AttemptSaved'):('save','CARLOS ESPÍ','RADU'),(89,'RMA','AttemptSaved'):('save','ENDRICK','RADU')}
EXTRA={(39,'RMA','Miss'):",pen:1,over:1"}
# Espí's header is blocked by Radu and he scores the rebound in the same minute: the save lands just before the goal
NUDGE={(85,'RMA','AttemptSaved'):-0.3}
# FotMob's official xG treats the header and the rebound as one chance: 1-(1-0.4396)(1-0.8783) = 0.93, so the rebound only adds
# 0.8783*(1-0.4396) to the live counter (xgc) and Madrid end on the official 3.76, not the raw per-shot 4.14
XGC={(85,'RMA'):round(0.8783*(1-0.4396),4)}
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def key(s): return (s['min'],s['team'],s['type'])
def beat(s): return key(s) in CHANCES and (s['min']!=89 or s['xg']>0.5) and (s['min']!=85 or s['xg']>0.4)
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to 94 (90+4)
    a=s['add'] or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for e in D['events']:
    T='A' if e.get('team')==HOME else 'E'
    if e['type']=='card' and e['card'] in('Red','YellowRed'):
        ev.append((e['min']+0.01,f"{{m:{e['min']},team:'{T}',type:'red',name:'{e['player'].upper()}',min:\"{e['min']}'\",why:'SECOND YELLOW'}}"))
for i,s in enumerate(shots):
    T='A' if s['team']==HOME else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Madrid attack +x, Celta attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else ''); k=(s['min'],s['team'])
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[k]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}{f',xgc:{XGC[k]}' if k in XGC else ''}}}"))
    elif beat(s):
        k,name,*by=CHANCES[key(s)]; m=round(clock(s)+NUDGE.get(key(s),0),2); by=f",by:'{by[0]}'" if by else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}{EXTRA.get(key(s),'')}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 45.5 = first-half stoppage; 90.5 / 90.75 = second-half stoppage (+4), stretched to the 94' clock end
mom=[[{90.5:91.5,90.75:93}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[94,0]]
emit('const EVENTS=[ // team: A = Real Madrid, E = Celta Vigo · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Madrid on top; 45.5 / 91.5+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
# sanity: per-shot xG vs FotMob's official totals
for per,lo,hi in (('FirstHalf',0,46),('SecondHalf',46,200),('All',0,200)):
    a=sum(s['xg'] for s in shots if s['team']==HOME and lo<=s['min']<hi); e=sum(s['xg'] for s in shots if s['team']!=HOME and lo<=s['min']<hi)
    a-=sum(s['xg']-XGC[(s['min'],s['team'])] for s in shots if s['type']=='Goal' and (s['min'],s['team']) in XGC and lo<=s['min']<hi)
    print(per,'live xG %.2f-%.2f'%(a,e),'official',D['stats'][per]['expected_goals'])
