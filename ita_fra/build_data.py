# match_data.json -> data.js (loaded by index.html) · Italy 3-1 France, UEFA Nations League A, Group 1, MD5
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
NAMES={(10,'FRA'):'MICHAEL OLISE',(26,'ITA'):'PIO ESPOSITO',(63,'ITA'):'DAVIDE FRATTESI',(75,'ITA'):'PIO ESPOSITO'}
WORD={(75,'ITA'):'BRACE'} # Pio Esposito's second: the callout lists both minutes
# big moments that didn't go in get their own beat (clock holds, callout): (minute, team, type) -> (beat, name, chip note or None)
CHANCES={(35,'FRA','Post'):('post','BRADLEY BARCOLA',None),(60,'ITA','Miss'):('miss','SEBASTIANO ESPOSITO','PENALTY OFF TARGET')}
STOP2=4 # second-half stoppage (FotMob AddedTime): the clock runs to 90+4
END=90+STOP2
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def beat(s): return (s['min'],s['team'],s['type']) in CHANCES
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to END
    a=s['add'] or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for s in shots:
    T='A' if s['team']=='ITA' else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Italy (home) attack +x, France attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else ''); k=(s['min'],s['team'])
        w=f",word:'{WORD[k]}'" if k in WORD else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[k]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}{w}}}"))
    elif beat(s):
        k,name,note=CHANCES[(s['min'],s['team'],s['type'])]; m=clock(s); note=f",note:'{note}'" if note else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{note}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 45.5 = first-half stoppage; 90.5 / 90.75 = second-half stoppage, stretched to the END clock
mom=[[{90.5:91.5,90.75:93}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[END,0]]
emit(f'const END={END}; // clock runs to 90+{STOP2}')
emit('const EVENTS=[ // team: A = Italy, E = France · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum per minute, + = Italy on top; 45.5 / 91.5+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
