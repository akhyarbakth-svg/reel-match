# match_data.json -> data.js (loaded by index.html)
# team A = Portugal (home, attacks +x), team E = Denmark (away, attacks -x)
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
NAMES={'Pierre-Emile Højbjerg':'PIERRE-EMILE HØJBJERG','Rasmus Højlund':'RASMUS HØJLUND','Joachim Andersen':'JOACHIM ANDERSEN','Bernardo Silva':'BERNARDO SILVA'}
WORD={('Rasmus Højlund',57):'BRACE'} # second goal for the same player: the callout lists both minutes
# big chances that didn't go in get their own beat (clock holds, callout): (minute, team, type) -> (beat, name)
CHANCES={(65,'POR','Miss'):('miss','TRINCÃO')}
def T(team): return 'A' if team=='POR' else 'E'
def clock(mn,add): # 90+N runs on the clock to END (95); no first-half stoppage shots today
    a=add or 0
    return 45+0.25*a if mn==45 and a else (90+a if mn==90 and a else mn)
def label(mn,add): return f"{mn}+{add}'" if add else f"{mn}'"
def xz(s): # FotMob x: 0..105 towards the goal attacked, y: 0..68
    sg=1 if s['team']=='POR' else -1; return round(sg*(s['x']-52.5),2), round(sg*(s['y']-34),2)
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
goal_shots=[s for s in shots if s['type']=='Goal']
ev,sh=[],[]
# goals come from the event feed (its minute is the one shown on the broadcast; the shot map has Højlund's first at 49')
for e in [e for e in D['events'] if e['type']=='goal']:
    s=next(s for s in goal_shots if s['player']==e['player'] and abs(clock(s['min'],s['add'])-clock(e['min'],e['add']))<=1.5)
    goal_shots.remove(s); x,z=xz(s); m=clock(e['min'],e['add'])
    lab=label(e['min'],e['add'])+(' (P)' if s['situation']=='Penalty' else ''); w=WORD.get((e['player'],e['min']))
    ev.append((m,f"{{m:{m},team:'{T(e['team'])}',type:'goal',name:'{NAMES[e['player']]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}"+(f",word:'{w}'" if w else '')+"}"))
for s in shots:
    if s['type']=='Goal': continue
    x,z=xz(s); k=(s['min'],s['team'],s['type'])
    if k in CHANCES:
        b,name=CHANCES[k]; m=clock(s['min'],s['add'])
        ev.append((m,f"{{m:{m},team:'{T(s['team'])}',type:'{b}',name:'{name}',min:\"{label(s['min'],s['add'])}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and (o['min'],o['team'],o['type']) not in CHANCES]
        m=clock(s['min'],s['add'])-0.5-0.3*(len(same)-1-same.index(s))
        kk={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T(s['team'])}',{s['xg']:.4f},{x},{z},'{kk}']")
ev=[s for _,s in sorted(ev,key=lambda p:p[0])]
# 45.5 = first-half stoppage (+2); 90.5 / 90.75 = second-half stoppage (+3), stretched to the 95' clock end
mom=[[{90.5:92,90.75:94}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[95,0]]
st=D['stats']['All']
OUT=['// generated by build_data.py from match_data.json ('+D['source']+')',
 'const EVENTS=[ // team: A = Portugal, E = Denmark · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];',
 '// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]',
 'const OTHER=['+','.join(sh)+'];',
 '// FotMob attacking momentum per minute, + = Portugal on top; 45.5 / 92+ = stoppage time',
 'const MOM='+json.dumps(mom,separators=(',',':'))+';',
 '// official full-match totals [Portugal, Denmark]',
 'const XG_FT=['+','.join(st['expected_goals'])+'], SHOTS_FT='+json.dumps(st['total_shots'])+', SOT_FT='+json.dumps(st['ShotsOnTarget'])+', POSS_FT='+json.dumps(st['BallPossesion'])+';']
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('\n'.join(OUT)+'\n'); print('wrote data.js')
