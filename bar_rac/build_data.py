# match_data.json -> data.js (loaded by index.html)
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
# A = Barcelona (attacks +x), E = Racing Santander (attacks -x)
NAMES={(8,'BAR'):'JOÃO CANCELO',(25,'BAR'):'RAPHINHA',(30,'RAC'):'MAGUETTE GUEYE',(36,'RAC'):'ASIER VILLALIBRE',
       (42,'BAR'):'RAPHINHA',(65,'RAC'):'YASSIR ZABIRI',(67,'BAR'):'RAPHINHA',(79,'BAR'):'GABRIEL JESUS',(89,'BAR'):'LAMINE YAMAL'}
WORD={(67,'BAR'):'HAT-TRICK'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, added, team, type) -> (beat, name[, keeper])
CHANCES={(19,None,'BAR','Miss'):('miss','KARIM ADEYEMI'),(45,0,'BAR','AttemptSaved'):('save','LAMINE YAMAL','AGIRREZABALA'),(45,1,'BAR','Miss'):('miss','KARIM ADEYEMI')}
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def beat(s): return (s['min'],s['add'],s['team'],s['type']) in CHANCES
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to END
    a=s['add'] or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for s in shots:
    sT='A' if s['team']=='BAR' else 'E'
    # FotMob x: 0..105 towards the goal the shooter attacks, y: 0..68. Barça attack +x, Racing attack -x.
    sg=1 if sT=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); k=(s['min'],s['team']); og=bool(s['ownGoal'])
        T=('E' if sT=='A' else 'A') if og else sT # an own goal counts for the other side; the location is already in their attacking half
        lab=label(s)+(' (P)' if s['situation']=='Penalty' else '')+(' (OG)' if og else '')
        extra=(f",og:1,crest:'{sT}'" if og else '')+(f",word:'{WORD[k]}'" if k in WORD else '')
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[k]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}{extra}}}"))
    elif beat(s):
        k,name,*by=CHANCES[(s['min'],s['add'],s['team'],s['type'])]; m=clock(s); by=f",by:'{by[0]}'" if by else ''
        pen=",pen:1" if s['situation']=='Penalty' else ''
        ev.append((m,f"{{m:{m},team:'{sT}',type:'{k}',name:'{name}',min:\"{label(s)}{' (P)' if pen else ''}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}{pen}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{sT}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev,key=lambda p:p[0])]
# 45.5 = first-half stoppage; 90.5 / 90.75 = second-half stoppage (+4), stretched to the 94' clock end
mom=[[{90.5:92,90.75:94}.get(m,m),round(v/100,2)] for m,v in D['momentum']]
emit('const EVENTS=[ // team: A = Barcelona, E = Racing Santander · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum per minute, + = Barcelona on top; 45.5 / 92+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
