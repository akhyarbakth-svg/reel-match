# match_data.json -> data.js (loaded by index.html)
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
# goals: (minute, added, team) -> on-screen name
NAMES={(8,None,'BAR'):'RAPHINHA',(23,None,'BAR'):'FERMÍN LÓPEZ',(41,None,'BAR'):'RAPHINHA',(45,1,'BAR'):'LAMINE YAMAL',
       (64,None,'BAR'):'LAMINE YAMAL',(81,None,'BAR'):'ANTHONY GORDON',(84,None,'ALA'):'MARIANO DÍAZ'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, team, type) -> (beat, name[, keeper])
CHANCES={(11,'ALA','Miss'):('miss','ABDERRAHMAN REBBACH'),(34,'BAR','Miss'):('miss','RAPHINHA'),(35,'BAR','AttemptSaved'):('save','LAMINE YAMAL','SIVERA')}
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def beat(s): return (s['min'],s['team'],s['type']) in CHANCES
def clock(s): # 45+N sits inside the first-half stoppage (45+5 -> 45.75) before the HT hold at 45.9; 90+N runs on the clock
    a=s['add'] or 0
    return round(45+0.15*a,2) if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for e in D['events']:
    T='A' if e.get('team')=='BAR' else 'E'
    if e['type']=='var': # none in this match
        ev.append((e['min']+0.01,f"{{m:{e['min']},team:'{T}',type:'var',name:'{e['player'].upper()}',min:\"{e['min']}'\",why:'{e['decision'][1].upper()}'}}"))
    elif e['type']=='card' and e['card'] in('Red','YellowRed'): # none in this match
        why='SECOND YELLOW' if e['card']=='YellowRed' else (e['reason'] or '').upper()
        ev.append((e['min']+0.01,f"{{m:{e['min']},team:'{T}',type:'red',name:'{e['player'].upper()}',min:\"{e['min']}'\",why:'{why}'}}"))
for s in shots:
    T='A' if s['team']=='BAR' else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Barcelona attack +x, Alavés attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else ''); k=(s['min'],s['add'] or None,s['team'])
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[k]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    elif beat(s):
        k,name,*by=CHANCES[(s['min'],s['team'],s['type'])]; m=clock(s); by=f",by:'{by[0]}'" if by else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 45.5 = first-half stoppage; 90.5 / 90.75 = second-half stoppage (+2), spread over the 91'-93' clock end
mom=[[{90.5:91,90.75:92}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[93,0]]
emit('const EVENTS=[ // team: A = Barcelona, E = Alavés · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Barcelona on top; 45.5 / 91+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
