# match_data.json -> data.js (loaded by index.html)
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
J=lambda s:json.dumps(s,ensure_ascii=False) # names like O'Reilly need quoting
NAMES={(9,'ARS'):'NONI MADUEKE',(38,'ARS'):'VIKTOR GYÖKERES',(90,'SLA'):'WIKTOR NOWAK'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, team, type) -> (beat, name[, keeper])
CHANCES={(24,'ARS','Miss'):('miss','MIKEL MERINO'),(27,'ARS','AttemptSaved'):('save','MIKEL MERINO','DOMCHAK')}
END=96 # 90+6: five minutes were added, Konečný's last shot came in the 96th
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def beat(s): return (s['min'],s['team'],s['type']) in CHANCES
def clock(s): # no first-half stoppage shots; 90+N runs on the clock to 96
    a=s['add'] or 0
    return 90+a if s['min']==90 and a else s['min']
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for s in shots:
    # FotMob x: 0..105 towards the goal the shooter's side attacks, y: 0..68. Slavia (A) attack +x, Arsenal (E) attack -x.
    T='A' if s['team']=='SLA' else 'E'
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s); k=(s['min'],s['team'])
        if s['ownGoal']: # own goal: the goal counts for the other side, at the shooter's own end; no shot, no xG (none today)
            ev.append((m,f"{{m:{m},team:'{'E' if T=='A' else 'A'}',type:'goal',og:1,name:{J(NAMES[k])},min:\"{lab} (OG)\",xg:0,x:{x},z:{z}}}"))
        else:
            ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:{J(NAMES[k])},min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    elif beat(s):
        k,name,*by=CHANCES[(s['min'],s['team'],s['type'])]; m=clock(s); by=f",by:{J(by[0])}" if by else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:{J(name)},min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        if s['min']>=46: m=max(m,46.1) # a 46' shot stays after the half-time hold at 45.9
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 45.5 = first-half stoppage (+1); 90.5 / 90.75 = second-half stoppage (+5, played to 90+6), stretched to the 96' clock end
mom=[[{90.5:93,90.75:96}.get(m,m),round(v/100,2)] for m,v in D['momentum']]
emit('const END='+str(END)+'; // clock runs to 90+6')
emit('const EVENTS=[ // team: A = Slavia Prague, E = Arsenal · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Slavia on top; 45.5 / 93 / 96 = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
