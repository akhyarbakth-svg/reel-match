# match_data.json -> data.js (loaded by index.html)
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
A='GER' # team 'A' (home, attacks +x, nearest the camera); the other side is 'E'
NAMES={'Derry Scherhant':'DERRY SCHERHANT','Florian Wirtz':'FLORIAN WIRTZ','Nico Schlotterbeck':'NICO SCHLOTTERBECK','Brajan Gruda':'BRAJAN GRUDA'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, team, type) -> (beat, name[, keeper])
CHANCES={(25,'NED','Miss'):('miss','DONYELL MALEN'),(32,'GER','Post'):('post','DERRY SCHERHANT')}
ADDED=2 # second-half stoppage (FotMob AddedTime event); the clock ends on 90+2
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def beat(s): return (s['min'],s['team'],s['type']) in CHANCES
def clock(s): # 90+N runs on the clock to the end
    a=s['add'] or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
# goal minutes come from the match events (official), the shot map can sit a minute early (Gruda: shot 77', goal 78')
GOALEV=[e for e in D['events'] if e['type']=='goal']
def goal_min(s):
    e=next(e for e in GOALEV if e['player']==s['player'] and e['team']==s['team'] and abs(e['min']-s['min'])<=1); GOALEV.remove(e); return {'min':e['min'],'add':e['add']}
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for s in shots:
    if s['type']=='Goal': s.update(goal_min(s))
for s in shots:
    T='A' if s['team']==A else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Team A attacks +x, team E attacks -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else '')
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[s['player']]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    elif beat(s):
        k,name,*by=CHANCES[(s['min'],s['team'],s['type'])]; m=clock(s); by=f",by:'{by[0]}'" if by else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        if s['min']==46: m=46.2+0.3*same.index(s) # second-half kick-off minute: stay after the HT hold at 45.9
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 90.5 / 90.75 = second-half stoppage (+2), stretched over the 90+1 / 90+2 clock
mom=[[{90.5:91.2,90.75:92.2}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[90+ADDED+0.75,0]]
emit('const EVENTS=[ // team: A = Germany, E = Netherlands · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Germany on top; 91+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
