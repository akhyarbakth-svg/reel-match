# match_data.json -> data.js (loaded by index.html) · France 2-1 Türkiye, UEFA Nations League A1 MD6
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
NAMES={(80,'FRA'):'JUNIOR KROUPI',(90,'TUR'):'ABDÜLKERIM BARDAKCI'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, team, xG>=) -> (beat, name[, keeper])
CHANCES={(21,'FRA'):('save','BRADLEY BARCOLA','ÖZER'),(35,'TUR'):('save','İSMAIL YÜKSEK','MAIGNAN'),
         (49,'FRA'):('miss','BRADLEY BARCOLA'),(64,'FRA'):('save','KYLIAN MBAPPÉ','ÖZER')}
VARN={'Kylian Mbappé':'KYLIAN MBAPPÉ','Arda Güler':'ARDA GÜLER'}
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def beat(s): return (s['min'],s['team']) in CHANCES and s['xg']>=0.25 # only the big one in each listed minute
def clock(s): # no first-half stoppage shots; 90+N runs on the clock to 94
    a=s['add'] or 0
    return 90+a if s['min']==90 and a else s['min']
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for e in D['events']:
    T='A' if e.get('team')=='FRA' else 'E'
    if e['type']=='var': # both ruled out for offside (FotMob decision: ['Goal ruled out', 'offside'])
        ev.append((e['min']+0.01,f"{{m:{e['min']},team:'{T}',type:'var',name:'{VARN[e['player']]}',min:\"{e['min']}'\",why:'{e['decision'][1].upper()}'}}"))
for s in shots:
    T='A' if s['team']=='FRA' else 'E'
    # FotMob x: 0..105 towards the goal the shooter attacks, y: 0..68. France attack +x, Türkiye attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal' and s['ownGoal']:
        # Topçu's own goal: Türkiye's touch into their own (+x) net counts for France. No xG (not a France shot), og flag keeps it out of the shot count
        ev.append((s['min'],f"{{m:{s['min']},team:'A',type:'goal',og:1,name:'EMIRHAN TOPÇU',min:\"{label(s)} OG\",xg:0,x:{x},z:{z}}}"))
    elif s['type']=='Goal':
        m=clock(s); lab=label(s); k=(s['min'],s['team'])
        ev.append((m+0.02,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[k]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    elif beat(s):
        k,name,*by=CHANCES[(s['min'],s['team'])]; m=clock(s)+(0.35 if (s['min'],s['team'])==(49,'FRA') else 0) # Barcola's 0.86 comes seconds after the own goal
        by=f",by:'{by[0]}'" if by else ''
        ev.append((m+0.03,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 90.5 / 90.75 = second-half stoppage (+4), stretched to the 94' clock end
mom=[[{90.5:92,90.75:93.5}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[94,0]]
emit('const EVENTS=[ // team: A = France, E = Türkiye · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = France on top; 92+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
