# FotMob match page (__NEXT_DATA__, Opta data) -> match_data.json + data.js
# usage: python -I fetch_data.py <fotmob match url | saved .html>
# Friendlies have no shot map / momentum on FotMob, so this keeps goals, cards, subs, lineups, ratings and team stats.
import json,os,re,sys,urllib.request
H=os.path.dirname(os.path.abspath(__file__))
src=sys.argv[1]
if src.startswith('http'):
    req=urllib.request.Request(src,headers={'User-Agent':'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/140.0 Safari/537.36'})
    html=urllib.request.urlopen(req,timeout=30).read().decode('utf-8')
else: html=open(src,encoding='utf-8').read()
pp=json.loads(re.search(r'<script id="__NEXT_DATA__" type="application/json">(.*?)</script>',html,re.S).group(1))['props']['pageProps']
g,c=pp['general'],pp['content']
CODE={6706:'ARG',5796:'URU'}
home,away=CODE[g['homeTeam']['id']],CODE[g['awayTeam']['id']]
events=[]
for e in c['matchFacts']['events']['events']:
    t=home if e.get('isHome') else away
    base={'min':e['time'],'add':e.get('overloadTime') or 0,'team':t}
    if e['type']=='Goal':
        # FotMob files an own goal under the team it counts for; the player is from the other side
        events.append({**base,'type':'goal','player':e['nameStr'],'ownGoal':bool(e.get('ownGoal')),
                       'assist':(e.get('assistStr') or '').replace('assist by ','') or None})
    elif e['type']=='Card': events.append({**base,'type':'card','card':e['card'],'player':e['nameStr']})
    elif e['type']=='Substitution':
        sw=e.get('swap') or []
        events.append({**base,'type':'sub','on':sw[0]['name'] if sw else None,'off':sw[1]['name'] if len(sw)>1 else None})
def side(t):
    T=c['lineup'][t]
    return {'formation':T.get('formation'),'rating':T.get('rating'),
            'starters':[{'no':p.get('shirtNumber'),'name':p['name'],'rating':(p.get('performance') or {}).get('rating'),
                         'x':p['horizontalLayout']['x'],'y':p['horizontalLayout']['y']} for p in T['starters']]}
stats={per:{r['key']:r['stats'] for grp in c['stats']['Periods'][per]['stats'] for r in grp['stats'] if r.get('stats') and r['stats'][0] is not None}
       for per in c['stats']['Periods']}
ib=c['matchFacts']['infoBox']; potm=c['matchFacts'].get('playerOfTheMatch') or {}
out={'source':f"FotMob match {g['matchId']} (Opta data)",
     'match':f"{g['homeTeam']['name']} {pp['header']['status']['scoreStr'].replace(' ','')} {g['awayTeam']['name']}, {g['leagueName']}, {g['matchTimeUTC']}",
     'home':home,'away':away,'kickoff':g['matchTimeUTC'],'stadium':ib['Stadium']['name'],'city':ib['Stadium']['city'],
     'referee':(ib.get('Referee') or {}).get('text'),
     'potm':{'name':(potm.get('name') or {}).get('fullName'),'rating':(potm.get('rating') or {}).get('num'),'team':CODE.get(potm.get('teamId'))},
     'events':events,'lineup':{home:side('homeTeam'),away:side('awayTeam')},'stats':stats}
json.dump(out,open(os.path.join(H,'match_data.json'),'w',encoding='utf-8'),ensure_ascii=False,indent=1)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by fetch_data.py from FotMob (Opta data)\nconst MATCH='+json.dumps(out,ensure_ascii=False)+';\n')
print('wrote match_data.json + data.js:',out['match'],len(events),'events')
