# match_data.json -> data.js (loaded by index.html)  ·  Inter Miami 3-3 Charlotte FC, MLS, 7 Nov 2026
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
# goals: (minute, minAdded, team) -> (name[, callout word])
NAMES={(14,None,'MIA'):('IAN FRAY',),(33,None,'MIA'):('LUIS SUÁREZ',),(42,None,'MIA'):('RODRIGO DE PAUL',),
       (50,None,'CLT'):('LIEL ABADA',),(55,None,'CLT'):('LIEL ABADA','BRACE'),(90,0,'CLT'):('RODOLFO ALOKO',)}
# chances that didn't go in but get their own beat (clock holds, callout): (minute, minAdded, team, type) -> (beat, name[, keeper])
CHANCES={(90,0,'CLT','Post'):('post','TYGER SMALLS'),(90,2,'MIA','Post'):('post','LIONEL MESSI'),(90,5,'CLT','Miss'):('miss','RODOLFO ALOKO')}
def key(s): return (s['min'],s['add'],s['team'])
def beat(s): return (*key(s),s['type']) in CHANCES
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to END (98)
    a=s['add'] or 0
    return 45+0.16*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
order={id(s):i for i,s in enumerate(D['shots'])} # FotMob lists same-minute shots in the order they happened
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0,order[id(s)]))
ev,sh,OUT=[],[],[]
seen={} # beats on the same clock minute (Smalls's post, then Aloko's equaliser, both 90') are spaced 0.3' apart
for s in shots:
    T='A' if s['team']=='MIA' else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Miami attack +x, Charlotte attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal' or beat(s):
        c=clock(s); n=seen.get(c,0); seen[c]=n+1; m=round(c+0.3*n,2)
        if s['type']=='Goal':
            name,*word=NAMES[key(s)]; lab=label(s)+(' (P)' if s['situation']=='Penalty' else ''); w=f",word:'{word[0]}'" if word else ''
            ev.append(f"{{m:{m},team:'{T}',type:'goal',name:'{name}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}{w}}}")
        else:
            k,name,*by=CHANCES[(*key(s),s['type'])]; by=f",by:'{by[0]}'" if by else ''
            ev.append(f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}}}")
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
# 45.5 = first-half stoppage; 90.5 / 90.75 = second-half stoppage (about +7), stretched to the 98' clock end
mom=[[{90.5:93,90.75:96}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[98,0]]
OUT.append('const EVENTS=[ // team: A = Inter Miami, E = Charlotte FC · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
OUT.append('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
OUT.append('const OTHER=['+','.join(sh)+'];')
OUT.append('// FotMob attacking momentum (xT model) per minute, + = Miami on top; 45.5 / 93+ = stoppage time')
OUT.append('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
