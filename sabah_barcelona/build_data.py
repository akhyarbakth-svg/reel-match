# match_data.json -> data.js (loaded by index.html)
# team A = Sabah (home, attacks +x), E = Barcelona (attacks -x; the camera sits behind Barça's attacking end)
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
NAMES={(31,'BAR'):'ANTHONY GORDON',(51,'BAR'):'ANTHONY GORDON',(55,'BAR'):'KARIM ADEYEMI',(60,'BAR'):'GABRIEL JESUS',(63,'SAB'):'JOY-LANCE MICKELS'}
WORD={(51,'BAR'):'BRACE'} # Gordon's second: the chip lists both minutes
# chances that didn't go in get their own beat (clock holds, callout): (minute, team, type, player) -> (beat, name[, by])
CHANCES={(9,'SAB','AttemptSaved','Xayal Əliyev'):('save','XAYAL ƏLIYEV','JOAN GARCÍA'),
         (27,'SAB','Post','Ivan Lepinjica'):('post','IVAN LEPINJICA'),
         (43,'BAR','Miss','Karim Adeyemi'):('miss','KARIM ADEYEMI'),
         (54,'BAR','Miss','Gabriel Jesus'):('miss','GABRIEL JESUS'),
         (60,'BAR','AttemptSaved','Gabriel Jesus'):('save','GABRIEL JESUS','LINE'), # FotMob: isSavedOffLine, no keeper
         (72,'SAB','Miss','Joy-Lance Mickels'):('miss','JOY-LANCE MICKELS'),
         (80,'BAR','Post','Karim Adeyemi'):('post','KARIM ADEYEMI')}
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def key(s): return (s['min'],s['team'],s['type'],s['player'])
def beat(s): return key(s) in CHANCES
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to END (90+2)
    a=s['add'] or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for i,s in enumerate(shots):
    T='A' if s['team']=='SAB' else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Sabah attack +x, Barcelona attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else ''); k=(s['min'],s['team'])
        w=f",word:'{WORD[k]}'" if k in WORD else ''
        ev.append((m,i,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[k]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}{w}}}"))
    elif beat(s):
        k,name,*by=CHANCES[key(s)]; m=clock(s); by=f",by:'{by[0]}'" if by else ''
        ev.append((m,i,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for *_,s in sorted(ev)] # same minute keeps FotMob's shot order (60': cleared off the line, then the rebound goes in)
# 45.5 = first-half stoppage; 90.5 / 90.75 = second-half stoppage (+2), stretched to the 92' clock end
mom=[[{90.5:91,90.75:91.6}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[92,0]]
emit('const EVENTS=[ // team: A = Sabah, E = Barcelona · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Sabah on top; 45.5 / 91+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
