# match_data.json -> data.js (loaded by index.html) · Villarreal 0-4 Paris Saint-Germain, Champions League MD4, 3 Nov 2026
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
A,E=D['home'],D['away'] # A = Villarreal (home, attacks +x), E = PSG (attacks -x)
# goal scorer display names: (minute, team) -> name; anything not listed falls back to FotMob's name in capitals
NAMES={}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, team, type) -> (beat, name[, keeper])
CHANCES={}
# FotMob VAR decision -> callout word / chip / name line
VARC={'Penalty cancelled':('NO PENALTY','PENALTY CANCELLED',None),'Goal ruled out':('NO GOAL','GOAL RULED OUT',None)}
REDN={}
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
ADD2=max([e['minutes'] for e in D['events'] if e['type']=='added' and e['min']==90]+[4]) # second-half stoppage: the clock runs to 90+ADD2
END=90+ADD2
def beat(s): return (s['min'],s['team'],s['type']) in CHANCES
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to END
    a=s['add'] or 0
    return 45+0.2*a if s['min']==45 and a else (min(90+a,END-0.3) if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for e in D['events']:
    T='A' if e.get('team')==A else 'E'
    if e['type']=='var':
        dec=e['decision']; word,what,name=VARC[dec[0]]; why=dec[1].upper() if len(dec)>1 else ''
        ev.append((e['min']+0.01,f"{{m:{e['min']},team:'{T}',type:'var',name:'{name or e['player'].upper()}',min:\"{e['min']}'\",word:'{word}',what:'{what}',why:'{why}'}}"))
    elif e['type']=='card' and e['card'] in('Red','YellowRed'):
        why='SECOND YELLOW' if e['card']=='YellowRed' else (e['reason'] or '').upper()
        ev.append((e['min']+0.01,f"{{m:{e['min']},team:'{T}',type:'red',name:'{REDN.get(e['player'],e['player'].upper())}',min:\"{e['min']}'\",why:'{why}'}}"))
for i,s in enumerate(shots):
    T='A' if s['team']==A else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Villarreal attack +x, PSG attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else '')+(' (OG)' if s['ownGoal'] else ''); k=(s['min'],s['team'])
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES.get(k,s['player'].upper())}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    elif beat(s):
        k,name,*by=CHANCES[(s['min'],s['team'],s['type'])]; m=clock(s); by=f",by:'{by[0]}'" if by else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        if s['min']>=46: m=max(m,45.95) # a 46' shot is second half: keep it after the HT hold at 45.9
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 45.5 = first-half stoppage; 90.5 / 90.75 = second-half stoppage, stretched to the END clock
mom=[[{90.5:90+0.45*ADD2,90.75:90+0.85*ADD2}.get(m,m),round((v or 0)/100,2)] for m,v in D['momentum']]+[[END,0]]
emit(f'const END={END}; // clock runs to 90+{ADD2}')
emit('const EVENTS=[ // team: A = Villarreal, E = Paris Saint-Germain · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Villarreal on top; 45.5 / 90.5+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
