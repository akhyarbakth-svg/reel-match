# match_data.json -> data.js (loaded by index.html) · England 2-1 Croatia, UEFA Nations League A3 MD5, 12 Nov 2026
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
A,E='ENG','CRO' # A = England (attacks +x, nearest the camera), E = Croatia
NAMES={(24,'ENG'):'MORGAN ROGERS',(59,'CRO'):'PETAR SUČIĆ',(64,'ENG'):'HARRY KANE'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, added, team, type) -> (beat, name)
# Kane's 51' has no keeperId in FotMob: it was blocked by an outfielder, not saved
CHANCES={(51,None,'ENG','AttemptSaved'):('block','HARRY KANE'),(87,None,'CRO','Miss'):('miss','JOŠKO GVARDIOL'),
         (90,2,'CRO','Miss'):('miss','ANTE BUDIMIR'),(90,4,'ENG','Miss'):('miss','MORGAN ROGERS')}
ev,sh,OUT=[],[],[]
def key(s): return (s['min'],s['add'],s['team'],s['type'])
def beat(s): return key(s) in CHANCES and (s['player'].upper()==CHANCES[key(s)][1]) # 90+2 also has a Vušković miss
def clock(s): # no first-half stoppage shots; 90+N runs on the clock to END
    a=s['add'] or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for s in shots:
    T='A' if s['team']==A else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. England attack +x, Croatia attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else ''); k=(s['min'],s['team'])
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[k]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    elif beat(s):
        k,name=CHANCES[key(s)]; m=clock(s)
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# FotMob stoppage samples 90.5 / 90.75 (+4 added) stretched to the 95' clock end
mom=[[{90.5:92,90.75:94}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[95,0]]
OUT.append('const EVENTS=[ // team: A = England, E = Croatia · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
OUT.append('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
OUT.append('const OTHER=['+','.join(sh)+'];')
OUT.append('// FotMob attacking momentum (xT model) per minute, + = England on top; 92+ = stoppage time')
OUT.append('const MOM='+json.dumps(mom,separators=(',',':'))+';')
st=D['stats']['All']
OUT.append('// FotMob official full-match totals (per-shot xG sums to 2.74 / 1.31; the live counter is scaled to land on these)')
OUT.append('const XG_FT={A:'+st['expected_goals'][0]+',E:'+st['expected_goals'][1]+'};')
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json\n'+'\n'.join(OUT)+'\n'); print('wrote data.js')
