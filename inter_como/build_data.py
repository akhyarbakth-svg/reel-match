# match_data.json -> data.js (loaded by index.html) · Inter 2-0 Como, Serie A MD11
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
NAMES={(12,'INT'):'PIO ESPOSITO',(19,'INT'):'MARCUS THURAM'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, team, type, player) -> (beat, name)
# FotMob: 4 big chances for Inter, 2 missed (Thuram and Dimarco, both in the 17th minute); Paz's 83' post is Como's best look
CHANCES={(17,'INT','Miss','Marcus Thuram'):('miss','MARCUS THURAM'),(17,'INT','Miss','Federico Dimarco'):('miss','FEDERICO DIMARCO'),
         (83,'COM','Post','Nico Paz'):('post','NICO PAZ')}
STOP2=3 # second-half stoppage (+3): the clock runs to 93
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def key(s): return (s['min'],s['team'],s['type'],s['player'])
def beat(s): return key(s) in CHANCES
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to 93
    a=s['add'] or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for e in D['events']:
    T='A' if e.get('team')=='INT' else 'E'
    if e['type']=='card' and e['card'] in('Red','YellowRed'): raise SystemExit('red card in data: add a REDN name map') # none today (one yellow: Esposito 72')
    if e['type']=='var': raise SystemExit('VAR call in data: add a VARN name map') # none today
beats_seen={}
for s in shots:
    T='A' if s['team']=='INT' else 'E'
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Inter attack +x, Como attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else ''); k=(s['min'],s['team'])
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{NAMES[k]}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    elif beat(s):
        k,name=CHANCES[key(s)]; n=beats_seen.get(clock(s),0); beats_seen[clock(s)]=n+1
        m=round(clock(s)+0.3*n,2) # two beats in one minute (Thuram, then Dimarco, in FotMob's order) play back to back
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 45.5 = first-half stoppage; 90.5 / 90.75 = second-half stoppage (+3), stretched to the 93' clock end
mom=[[{90.5:91.5,90.75:92.5}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[90+STOP2,0]]
emit('const EVENTS=[ // team: A = Inter, E = Como · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Inter on top; 45.5 / 91.5+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
