# match_data.json -> data.js (loaded by index.html)
import json,os
H=os.path.dirname(os.path.abspath(__file__))
D=json.load(open(os.path.join(H,'match_data.json'),encoding='utf-8'))
# team A = Lens (home, attacks +x), E = Como (away, attacks -x; the camera sits behind Como's attacking end)
TEAM={'LEN':'A','COM':'E'}
# big chances that didn't go in get their own beat (clock holds, callout): (minute, team, type) -> (beat, name, keeper)
# Lens's best chance of the night (Ivanović 0.37) and Como's biggest miss (Da Cunha 0.42), both saved
CHANCES={(34,'LEN','AttemptSaved'):('save','FRANJO IVANOVIĆ','BUTEZ'),(52,'COM','AttemptSaved'):('save','LUCAS DA CUNHA','RISSER')}
ev,sh=[],[]
OUT=[]
def emit(t): OUT.append(t)
def beat(s): return (s['min'],s['team'],s['type']) in CHANCES
def clock(s): # 45+N sits inside the first-half stoppage before the HT hold at 45.9; 90+N runs on the clock to 93
    a=s['add'] or 0
    return 45+0.25*a if s['min']==45 and a else (90+a if s['min']==90 and a else s['min'])
def label(s):
    a=s['add']; return f"{s['min']}+{a}'" if a else f"{s['min']}'"
shots=sorted(D['shots'],key=lambda s:(s['min'],s['add'] or 0))
for e in D['events']:
    if e['type']=='var': # 16': a Lens penalty, cancelled on review (FotMob decision: ['Penalty cancelled'])
        T=TEAM[e['team']]; what=e['decision'][0].upper()
        ev.append((e['min']+0.01,f"{{m:{e['min']},team:'{T}',type:'var',name:'PENALTY TO LENS',min:\"{e['min']}'\",word:'NO PENALTY',what:'{what}'}}"))
tally={}
for s in shots:
    T=TEAM[s['team']]
    # FotMob x: 0..105 towards the goal attacked, y: 0..68. Lens attack +x, Como attack -x.
    sg=1 if T=='A' else -1; x=round(sg*(s['x']-52.5),2); z=round(sg*(s['y']-34),2)
    if s['type']=='Goal':
        m=clock(s); lab=label(s)+(' (P)' if s['situation']=='Penalty' else '')
        tally[s['player']]=tally.get(s['player'],0)+1; word=",word:'HAT-TRICK'" if tally[s['player']]==3 else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'goal',name:'{s['player'].upper()}',min:\"{lab}\",xg:{s['xg']:.4f},x:{x},z:{z}{word}}}"))
    elif beat(s):
        k,name,*by=CHANCES[(s['min'],s['team'],s['type'])]; m=clock(s); by=f",by:'{by[0]}'" if by else ''
        ev.append((m,f"{{m:{m},team:'{T}',type:'{k}',name:'{name}',min:\"{label(s)}\",xg:{s['xg']:.4f},x:{x},z:{z}{by}}}"))
    else:
        # same-minute shots pop in sequence just before the minute (and before any beat on it)
        same=[o for o in shots if o['min']==s['min'] and (o['add'] or 0)==(s['add'] or 0) and o['type']!='Goal' and not beat(o)]
        m=clock(s)-0.5-0.3*(len(same)-1-same.index(s))
        k={'Post':'W','AttemptSaved':'B' if s['blocked'] else 'S','Miss':'M'}[s['type']]
        sh.append(f"[{round(m,2)},'{T}',{s['xg']:.4f},{x},{z},'{k}']")
ev=[s for _,s in sorted(ev)]
# 45.5 = first-half stoppage (+4); 90.5 / 90.75 = second-half stoppage (+3), stretched to the 93' clock end
mom=[[{90.5:91.5,90.75:92.5}.get(m,m),round(v/100,2)] for m,v in D['momentum']]+[[93,0]]
emit('const EVENTS=[ // team: A = Lens, E = Como · xG + shot location from FotMob (Opta)\n '+',\n '.join(ev)+'];')
emit('// every other shot: [clock minute, team, xG, x, z, W=woodwork S=saved B=blocked M=off target]')
emit('const OTHER=['+','.join(sh)+'];')
emit('// FotMob attacking momentum (xT model) per minute, + = Lens on top; 45.5 / 91.5+ = stoppage time')
emit('const MOM='+json.dumps(mom,separators=(',',':'))+';')
NL=chr(10)
open(os.path.join(H,'data.js'),'w',encoding='utf-8').write('// generated by build_data.py from match_data.json'+NL+NL.join(OUT)+NL); print('wrote data.js')
